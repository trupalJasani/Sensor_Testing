"""
Exports a fitted scikit-learn RandomForestClassifier (binary) to the flat C
tables used by components/blight_forecast/blight_forecast.c.

Why a custom exporter instead of emlearn's int16 export:
- thresholds stay float32 and are rounded DOWN from scikit-learn's double
  thresholds, so `x <= thr` takes exactly the same branch as scikit-learn
  for every float32 input (the int16 truncation of issue F4 cannot occur);
- leaves store the class-1 probability, so the node outputs a score that
  can be thresholded and reported, not only a hard class.
"""

import datetime as _dt

import numpy as np

LEAF = -1


def _round_down_f32(x):
    """Largest float32 value <= x (x is a Python/NumPy double)."""
    f = np.float32(x)
    if float(f) > float(x):
        f = np.nextafter(f, np.float32(-np.inf), dtype=np.float32)
    return f


def forest_tables(rf):
    """Flattens all trees into global node arrays. Returns a dict."""
    roots, feats, vals, lefts, rights = [], [], [], [], []
    max_depth = 0
    for est in rf.estimators_:
        tr = est.tree_
        base = len(feats)
        roots.append(base)
        max_depth = max(max_depth, int(est.get_depth()))
        value = tr.value[:, 0, :]
        frac = value / value.sum(axis=1, keepdims=True)
        cls1 = list(rf.classes_).index(1)
        for n in range(tr.node_count):
            if tr.children_left[n] == -1:
                feats.append(LEAF)
                vals.append(np.float32(frac[n, cls1]))
                lefts.append(0)
                rights.append(0)
            else:
                feats.append(int(tr.feature[n]))
                vals.append(_round_down_f32(tr.threshold[n]))
                lefts.append(base + int(tr.children_left[n]))
                rights.append(base + int(tr.children_right[n]))
    return dict(roots=roots, feats=feats, vals=vals, lefts=lefts, rights=rights,
                max_depth=max_depth, n_nodes=len(feats), n_trees=len(roots))


def table_bytes(tab):
    """Flash bytes of the generated tables."""
    idx = 2 if tab["n_nodes"] < 65536 else 4
    return tab["n_nodes"] * (1 + 4 + 2 * idx) + tab["n_trees"] * idx


def _fmt_float(v):
    s = np.format_float_positional(np.float32(v), unique=True, trim="0")
    if "." not in s and "e" not in s:
        s += ".0"
    return s + "f"


def _rows(values, fmt, per_line=12):
    out = []
    for i in range(0, len(values), per_line):
        out.append("    " + ", ".join(fmt(v) for v in values[i:i + per_line]) + ",")
    return "\n".join(out)


def write_header(rf, path, threshold, feature_names, model_id, notes):
    """Writes blight_forecast_model.h."""
    tab = forest_tables(rf)
    idx_t = "uint16_t" if tab["n_nodes"] < 65536 else "uint32_t"
    thr = _round_down_f32(threshold)
    lines = []
    lines.append("/**")
    lines.append(" * @file  blight_forecast_model.h")
    lines.append(" * @brief GENERATED by ml_forecast/export_c.py - do not edit by hand.")
    lines.append(f" *        Model: {model_id}")
    for n in notes:
        lines.append(f" *        {n}")
    lines.append(" *        Features (index: name):")
    for i, name in enumerate(feature_names):
        lines.append(f" *          {i:2d}: {name}")
    lines.append(f" *        Generated {_dt.date.today().isoformat()}.")
    lines.append(" */")
    lines.append("#ifndef BLIGHT_FORECAST_MODEL_H")
    lines.append("#define BLIGHT_FORECAST_MODEL_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append(f'#define BF_MODEL_ID "{model_id}"')
    lines.append(f"#define BF_MODEL_N_TREES {tab['n_trees']}u")
    lines.append(f"#define BF_MODEL_N_NODES {tab['n_nodes']}u")
    lines.append(f"#define BF_MODEL_MAX_DEPTH {tab['max_depth']}u")
    lines.append(f"#define BF_MODEL_THRESHOLD {_fmt_float(thr)}")
    lines.append(f"#define BF_MODEL_N_FEATURES {len(feature_names)}u")
    lines.append("")
    lines.append(f"static const {idx_t} bf_tree_root[BF_MODEL_N_TREES] = {{")
    lines.append(_rows(tab["roots"], str))
    lines.append("};")
    lines.append("")
    lines.append("/* Feature index per node; -1 = leaf. */")
    lines.append("static const int8_t bf_node_feature[BF_MODEL_N_NODES] = {")
    lines.append(_rows(tab["feats"], str, 24))
    lines.append("};")
    lines.append("")
    lines.append("/* Split threshold (go left if x <= value), or leaf probability. */")
    lines.append("static const float bf_node_value[BF_MODEL_N_NODES] = {")
    lines.append(_rows(tab["vals"], _fmt_float, 8))
    lines.append("};")
    lines.append("")
    lines.append(f"static const {idx_t} bf_node_left[BF_MODEL_N_NODES] = {{")
    lines.append(_rows(tab["lefts"], str, 16))
    lines.append("};")
    lines.append("")
    lines.append(f"static const {idx_t} bf_node_right[BF_MODEL_N_NODES] = {{")
    lines.append(_rows(tab["rights"], str, 16))
    lines.append("};")
    lines.append("")
    lines.append("#endif /* BLIGHT_FORECAST_MODEL_H */")
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    return tab


def write_golden(path, X, p, threshold, model_id):
    """Writes reference vectors (features + scikit-learn probability) for the
    C host test, so later edits of the C code are checked against Python."""
    lines = ["/**",
             " * @file  bf_golden_vectors.h",
             " * @brief GENERATED by ml_forecast/export_c.py: test-year feature rows and the",
             " *        scikit-learn probability for each. Used by test_blight_forecast.c.",
             f" *        Model: {model_id}",
             " */",
             "#ifndef BF_GOLDEN_VECTORS_H",
             "#define BF_GOLDEN_VECTORS_H",
             "",
             f"#define BF_GOLDEN_N {len(X)}u",
             f'#define BF_GOLDEN_MODEL_ID "{model_id}"',
             "",
             f"static const float bf_golden_x[BF_GOLDEN_N][{X.shape[1]}] = {{"]
    for row in X:
        lines.append("    { " + ", ".join(_fmt_float(v) for v in row) + " },")
    lines.append("};")
    lines.append("")
    lines.append("static const double bf_golden_p[BF_GOLDEN_N] = {")
    lines.append(_rows([float(v) for v in p], lambda v: repr(v), 4))
    lines.append("};")
    lines.append("")
    lines.append("#endif /* BF_GOLDEN_VECTORS_H */")
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
