#!/usr/bin/env python3
"""
make_episodes.py - generates main/ft_episodes.h for the forecast test firmware.

Picks three real summer episodes from the TEST years (2015-2024, never used
for training or model selection) of DWD station 04104 and writes, for each:
  - the hourly temperature / RH the node will replay (48 h history + 120 h),
    stored as the exact float32 values the training pipeline used;
  - for each of the 120 issue hours: the scikit-learn probability and
    warning from ml_forecast/results/predictions_test.csv, and the truth
    label y ("the next 24 h ARE a Smith day", from the DWD data).
It also writes tools/episodes.csv (same data plus the window flag) for
analyse_ft_log.py.

Episodes (anchor = DWD hour index, see the README):
  hit         2020-08-02 23:00 onset, the forest warned 11 h ahead
  miss        2023-07-26 22:00 onset, no warning before it
  false_alarm 2021-07-17 09:00, 19 h warning, no Smith day within 2-3 days

Run from this folder (needs pandas, numpy):
  python3 tools/make_episodes.py
"""
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.normpath(os.path.join(HERE, ".."))
NODE = os.path.normpath(os.path.join(PROJ, "..", "agri_node_test"))
sys.path.insert(0, os.path.join(NODE, "ml_forecast"))
import forecast_data as fd  # noqa: E402  (node's own pipeline module)

DWD = os.path.join(NODE, "main", "produkt_tu_stunde_19480101_20241231_04104.txt")
PRED = os.path.join(NODE, "ml_forecast", "results", "predictions_test.csv")
OUT_H = os.path.join(PROJ, "main", "ft_episodes.h")
OUT_CSV = os.path.join(HERE, "episodes.csv")

HISTORY_H = fd.HISTORY_H          # 48
N_ISSUE = 120                     # issue hours replayed per episode
LEAD_BEFORE = 36                  # issue hours before the anchor

# (name, anchor timestamp). Anchor = onset hour (window ending there is the
# first Smith day) for hit/miss, first warning hour for the false alarm.
EPISODES = [
    ("hit", "2020-08-02 23:00:00"),
    ("miss", "2023-07-26 22:00:00"),
    ("false_alarm", "2021-07-17 09:00:00"),
]


def f32_literal(v):
    """C literal that round-trips the float32 value exactly (9 significant digits)."""
    x = float(np.float32(v))
    s = "%.9g" % x
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def main():
    """Builds the episodes and writes the C header and the CSV."""
    df = fd.load_dwd(DWD)
    t32 = df["temp"].to_numpy(dtype=np.float32)
    r32 = df["rh"].to_numpy(dtype=np.float32)
    flag = fd.smith_window_flags(t32, r32)
    pred = pd.read_csv(PRED).set_index("end_index")
    thr = np.float32(0.26)

    rows = []
    c_eps = []
    for name, ts in EPISODES:
        anchor = int(df.index.get_loc(pd.Timestamp(ts)))
        first_issue = anchor - LEAD_BEFORE
        issues = np.arange(first_issue, first_issue + N_ISSUE)
        missing = [int(i) for i in issues if i not in pred.index]
        if missing:
            raise SystemExit(f"{name}: issue hours missing in predictions_test.csv: {missing[:5]}")
        raw = np.arange(first_issue - (HISTORY_H - 1), issues[-1] + 1)
        if not (np.all(np.isfinite(t32[raw])) and np.all(np.isfinite(r32[raw]))):
            raise SystemExit(f"{name}: NaN in the replay window")
        p = pred.loc[issues, "p_rf"].to_numpy(dtype=np.float64)
        y = pred.loc[issues, "y"].to_numpy(dtype=np.int64)
        warn = (p >= float(thr)).astype(np.int64)
        assert np.array_equal(warn.astype(bool), pred.loc[issues, "warn_rf"].to_numpy(dtype=bool)), name
        margin = float(np.min(np.abs(p - float(thr))))
        print(f"{name:12s} raw {df.index[raw[0]]} .. {df.index[raw[-1]]}  "
              f"issues {df.index[issues[0]]} .. {df.index[issues[-1]]}  "
              f"y=1: {int(y.sum())} h  warn: {int(warn.sum())} h  min|p-thr| {margin:.2e}")
        for k, i in enumerate(raw):
            j = k - (HISTORY_H - 1)
            rows.append(dict(episode=name, raw_hour=k, time=df.index[i], temp=float(t32[i]),
                             rh=float(r32[i]), window_flag=float(flag[i]),
                             issue=int(j >= 0),
                             p_ref=float(p[j]) if j >= 0 else np.nan,
                             warn_ref=int(warn[j]) if j >= 0 else -1,
                             y=int(y[j]) if j >= 0 else -1))
        c_eps.append(dict(name=name, start=str(df.index[raw[0]]), t=t32[raw], r=r32[raw],
                          p=p, y=y, warn=warn, anchor_issue=LEAD_BEFORE))

    pd.DataFrame(rows).to_csv(OUT_CSV, index=False)

    n_raw = HISTORY_H - 1 + N_ISSUE
    L = []
    L.append("/**")
    L.append(" * @file  ft_episodes.h")
    L.append(" * @brief GENERATED by tools/make_episodes.py - do not edit by hand.")
    L.append(" *        Three real DWD 04104 episodes from the test years for the")
    L.append(" *        on-device replay test. Values are the exact float32 inputs and")
    L.append(" *        scikit-learn outputs of ml_forecast (predictions_test.csv).")
    L.append(" */")
    L.append("#ifndef FT_EPISODES_H")
    L.append("#define FT_EPISODES_H")
    L.append("")
    L.append("#include <stdint.h>")
    L.append("")
    L.append(f"#define FT_N_EPISODES   {len(c_eps)}u")
    L.append(f"#define FT_N_RAW_HOURS  {n_raw}u   /* 47 history hours + {N_ISSUE} issue hours */")
    L.append(f"#define FT_N_ISSUE      {N_ISSUE}u")
    L.append("")
    L.append("/** One replay episode. Issue hour j uses raw hours j .. j+47. */")
    L.append("typedef struct")
    L.append("{")
    L.append("    const char  *name;              /**< hit / miss / false_alarm            */")
    L.append("    const char  *start;             /**< DWD time stamp of raw hour 0        */")
    L.append("    uint16_t     anchor_issue;      /**< issue index of the onset / alarm    */")
    L.append("    const float *temp_c;            /**< FT_N_RAW_HOURS hourly temperatures  */")
    L.append("    const float *rh_pct;            /**< FT_N_RAW_HOURS hourly humidities    */")
    L.append("    const double *p_ref;            /**< FT_N_ISSUE scikit-learn probabilities */")
    L.append("    const uint8_t *y;               /**< FT_N_ISSUE truth: next 24 h = Smith day */")
    L.append("} ft_episode_t;")
    L.append("")
    for k, e in enumerate(c_eps):
        L.append(f"/* Episode {k}: {e['name']}, raw hours from {e['start']} */")
        for arr, cname in ((e["t"], "temp"), (e["r"], "rh")):
            L.append(f"static const float ft_ep{k}_{cname}[FT_N_RAW_HOURS] = {{")
            vals = [f32_literal(v) for v in arr]
            for i in range(0, len(vals), 10):
                L.append("    " + ", ".join(vals[i:i + 10]) + ",")
            L.append("};")
        L.append(f"static const double ft_ep{k}_p[FT_N_ISSUE] = {{")
        vals = ["%.17g" % v for v in e["p"]]
        for i in range(0, len(vals), 4):
            L.append("    " + ", ".join(vals[i:i + 4]) + ",")
        L.append("};")
        L.append(f"static const uint8_t ft_ep{k}_y[FT_N_ISSUE] = {{")
        vals = [str(int(v)) for v in e["y"]]
        for i in range(0, len(vals), 30):
            L.append("    " + ", ".join(vals[i:i + 30]) + ",")
        L.append("};")
        L.append("")
    L.append("static const ft_episode_t ft_episodes[FT_N_EPISODES] = {")
    for k, e in enumerate(c_eps):
        L.append(f"    {{\"{e['name']}\", \"{e['start']}\", {e['anchor_issue']}u, "
                 f"ft_ep{k}_temp, ft_ep{k}_rh, ft_ep{k}_p, ft_ep{k}_y}},")
    L.append("};")
    L.append("")
    L.append("#endif /* FT_EPISODES_H */")
    with open(OUT_H, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote", OUT_H, "and", OUT_CSV)


if __name__ == "__main__":
    main()
